-- 2) Public directory RPC.
--    Deliberately exposes ONLY name, country and the public selection
--    code. It never exposes email, phone, application answers or IDs.
create or replace function public.womate_public_selected_directory()
returns jsonb
language sql
security definer
set search_path = public
stable
as $$
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'fullName', i.full_name,
        'selectionCode', i.public_code,
        'countryCode', coalesce(i.country_code,'AF'),
        'countryName', coalesce(i.country_name,'Africa (not specified)'),
        'selectionRank', i.selection_rank
      )
      order by coalesce(i.country_name,'ZZZ'), lower(i.full_name)
    ),
    '[]'::jsonb
  )
  from public.womate_selected_card_invites i
  where i.status='active'
    and i.programme_slug='she-leads-2026'
    and i.public_code is not null;
$$;

revoke all on function public.womate_public_selected_directory() from public;
grant execute on function public.womate_public_selected_directory() to anon, authenticated;

-- 3) Keep the existing manual Admin "Generate Selection Code" option.
--    The UI/signature does not change. New manually generated codes are
--    also stored as public_code, and country/rank are carried forward
--    from the previous record for that learner whenever available.
create or replace function public.womate_create_selected_card_invite(
    p_email text,
    p_full_name text,
    p_programme_slug text default 'she-leads-2026',
    p_programme_name text default 'She Leads Climate Mentorship Programme',
    p_cohort_label text default 'Cohort 2 · 2026',
    p_expires_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_code text;
    v_hash text;
    v_id uuid;
    v_email text;
    v_name text;
    v_slug text;
    v_country_code text;
    v_country_name text;
    v_selection_rank integer;
begin
    if auth.uid() is null
       or not public.canopy_is_womate_admin(auth.uid())
    then
        raise exception 'Admin access required.';
    end if;

    v_email := lower(trim(coalesce(p_email,'')));
    v_name := trim(coalesce(p_full_name,''));
    v_slug := coalesce(nullif(trim(p_programme_slug),''),'she-leads-2026');

    if v_email='' then raise exception 'Learner email is required.'; end if;
    if v_name='' then raise exception 'Learner full name is required.'; end if;
    if position('@' in v_email)<2 then raise exception 'Enter a valid learner email address.'; end if;

    select i.country_code, i.country_name, i.selection_rank
      into v_country_code, v_country_name, v_selection_rank
    from public.womate_selected_card_invites i
    where lower(i.email)=v_email
      and i.programme_slug=v_slug
    order by (i.status='active') desc, i.created_at desc
    limit 1;

    v_code := upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
    v_hash := md5(v_code);

    update public.womate_selected_card_invites
       set status='revoked'
     where lower(email)=v_email
       and programme_slug=v_slug
       and status='active';

    insert into public.womate_selected_card_invites(
        email,full_name,programme_slug,programme_name,cohort_label,
        code_hash,code_hint,public_code,
        country_code,country_name,selection_rank,
        status,expires_at,created_by
    )
    values(
        v_email,v_name,v_slug,
        coalesce(nullif(trim(p_programme_name),''),'She Leads Climate Mentorship Programme'),
        coalesce(nullif(trim(p_cohort_label),''),'Cohort 2 · 2026'),
        v_hash,right(v_code,4),v_code,
        v_country_code,v_country_name,v_selection_rank,
        'active',p_expires_at,auth.uid()
    )
    returning id into v_id;

    return jsonb_build_object(
        'id',v_id,
        'email',v_email,
        'full_name',v_name,
        'programme_slug',v_slug,
        'programme_name',coalesce(nullif(trim(p_programme_name),''),'She Leads Climate Mentorship Programme'),
        'cohort_label',coalesce(nullif(trim(p_cohort_label),''),'Cohort 2 · 2026'),
        'selection_code',v_code,
        'expires_at',p_expires_at
    );
end;
$$;

revoke all on function public.womate_create_selected_card_invite(text,text,text,text,text,timestamptz) from public;
